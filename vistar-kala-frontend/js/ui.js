async function loadUserProfile() {
    try {
        const res = await getProfileAPI();
        const user = res.user || {};
        const profile = res.profile || {};

        const nameInput = document.getElementById('prof-name');
        const phoneInput = document.getElementById('prof-phone');
        const roleEl = document.getElementById('prof-role');

        if (nameInput) nameInput.value = user.name || '';
        if (phoneInput) phoneInput.value = user.phone || '';
        if (roleEl) roleEl.innerText = (user.role || 'user').toUpperCase();

        const artisanSection = document.getElementById('prof-artisan-fields');
        const buyerSection = document.getElementById('prof-buyer-fields');

        if (user.role === 'artisan') {
            if (artisanSection) artisanSection.classList.remove('hidden');
            if (buyerSection) buyerSection.classList.add('hidden');
            const loc = document.getElementById('prof-artisan-loc');
            const craft = document.getElementById('prof-artisan-craft');
            const exp = document.getElementById('prof-artisan-exp');
            if (loc) loc.value = profile.location || '';
            if (craft) craft.value = profile.craftCategory || '';
            if (exp) exp.value = profile.experienceYears || '';
        } else {
            if (buyerSection) buyerSection.classList.remove('hidden');
            if (artisanSection) artisanSection.classList.add('hidden');
            const comp = document.getElementById('prof-buyer-company');
            const loc = document.getElementById('prof-buyer-loc');
            if (comp) comp.value = profile.companyName || '';
            if (loc) loc.value = profile.location || '';
        }
    } catch (err) {
        alert(`Failed to load profile: ${err.message}`);
    }
}

async function handleProfileSubmit(event) {
    if (event) event.preventDefault();

    const name = document.getElementById('prof-name')?.value.trim();
    const role = currentUser?.role;

    const payload = { name };

    if (role === 'artisan') {
        payload.artisan = {
            location: document.getElementById('prof-artisan-loc')?.value.trim(),
            craftCategory: document.getElementById('prof-artisan-craft')?.value.trim(),
            experienceYears: Number(document.getElementById('prof-artisan-exp')?.value || 0)
        };
    } else {
        payload.buyer = {
            companyName: document.getElementById('prof-buyer-company')?.value.trim(),
            location: document.getElementById('prof-buyer-loc')?.value.trim()
        };
    }

    try {
        const res = await updateProfileAPI(payload);
        if (res.user) {
            setAuthState(authToken, res.user);
            const badge = document.getElementById('user-badge');
            if (badge) badge.innerText = `${res.user.name || res.user.phone} (${res.user.role})`;
        }
        alert('Profile updated successfully!');
        closeProfileModal();
    } catch (err) {
        alert(`Profile update error: ${err.message}`);
    }
}
