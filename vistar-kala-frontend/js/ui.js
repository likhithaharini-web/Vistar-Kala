/**
 * Applies static dictionary translations across the entire page UI
 */
function applyTranslations(lang) {
    currentLang = lang;
    document.documentElement.lang = lang;

    const dict = i18n[lang] || i18n.en;

    // Update element texts with matching data-i18n attributes or IDs
    for (const key in dict) {
        const el = document.getElementById(key);
        if (el) {
            el.innerHTML = dict[key];
        }
        document.querySelectorAll(`[data-i18n="${key}"]`).forEach(elem => {
            elem.innerHTML = dict[key];
        });
    }

    // Trigger dynamic translation for dynamic API product titles/descriptions if needed
    if (typeof loadMarketplaceProducts === 'function') {
        loadMarketplaceProducts();
    }
}

function setLanguage(lang) {
    applyTranslations(lang);
}

/**
 * View Navigation
 */
function navigateTo(pageId) {
    currentView = pageId;

    const views = ['landing', 'artisan', 'b2b', 'login'];
    views.forEach(v => {
        const el = document.getElementById(`view-${v}`);
        if (el) {
            if (v === pageId) {
                el.classList.remove('hidden');
            } else {
                el.classList.add('hidden');
            }
        }
    });

    window.scrollTo({ top: 0, behavior: 'smooth' });

    if (pageId === 'b2b' && typeof loadMarketplaceProducts === 'function') {
        loadMarketplaceProducts();
    }
}

/**
 * Role Switch (Login Tab)
 */
function switchRole(role) {
    currentRole = role;
    const tabArtisan = document.getElementById('tab-role-artisan');
    const tabB2B = document.getElementById('tab-role-b2b');

    if (role === 'artisan') {
        if (tabArtisan) tabArtisan.className = 'py-3 font-bold text-gold-300 border-b-2 border-gold-400 text-xs sm:text-sm';
        if (tabB2B) tabB2B.className = 'py-3 font-medium text-stone-400 text-xs sm:text-sm';
    } else {
        if (tabB2B) tabB2B.className = 'py-3 font-bold text-gold-300 border-b-2 border-gold-400 text-xs sm:text-sm';
        if (tabArtisan) tabArtisan.className = 'py-3 font-medium text-stone-400 text-xs sm:text-sm';
    }
}

