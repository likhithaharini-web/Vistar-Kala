/**
 * Full-Page Global DOM Translation Engine
 */
function translateDOM(lang) {
    if (!lang) lang = currentLang || 'en';
    const dict = phraseDictionary[lang];

    // Translate document title
    if (lang === 'te') {
        document.title = "విస్తార్ కళా | హెరిటేజ్ కామర్స్ AI మార్కెట్‌ప్లేస్";
    } else if (lang === 'hi') {
        document.title = "विस्तार कला | विरासत वाणिज्य एआई";
    } else {
        document.title = "Vistar Kala | Heritage Commerce AI Marketplace";
    }

    const elements = document.querySelectorAll(
        'h1, h2, h3, h4, h5, h6, p, span, button, label, a, option, th, td, div, strong, em, b, input, textarea'
    );

    elements.forEach(elem => {
        if (elem.closest('#lang-select') || elem.tagName === 'SCRIPT' || elem.tagName === 'STYLE') return;

        // 1. Placeholder translation
        if (elem.hasAttribute('placeholder')) {
            if (!elem.dataset.origPlaceholder) {
                elem.dataset.origPlaceholder = elem.getAttribute('placeholder');
            }
            if (lang === 'en') {
                elem.setAttribute('placeholder', elem.dataset.origPlaceholder);
            } else if (dict) {
                const cleanPl = elem.dataset.origPlaceholder.replace(/\s+/g, ' ').trim();
                if (dict[cleanPl]) {
                    elem.setAttribute('placeholder', dict[cleanPl]);
                }
            }
        }

        // 2. Title translation
        if (elem.hasAttribute('title')) {
            if (!elem.dataset.origTitle) {
                elem.dataset.origTitle = elem.getAttribute('title');
            }
            if (lang === 'en') {
                elem.setAttribute('title', elem.dataset.origTitle);
            } else if (dict) {
                const cleanTi = elem.dataset.origTitle.replace(/\s+/g, ' ').trim();
                if (dict[cleanTi]) {
                    elem.setAttribute('title', dict[cleanTi]);
                }
            }
        }

        // 3. Child text nodes translation
        for (let i = 0; i < elem.childNodes.length; i++) {
            const node = elem.childNodes[i];
            if (node.nodeType === 3 /* Node.TEXT_NODE */) {
                const raw = node.nodeValue.trim();
                if (!raw) continue;
                const clean = raw.replace(/\s+/g, ' ').trim();

                // If not recorded yet, store original English text
                if (!node._origText) {
                    node._origText = clean;
                }

                const lookupKey = node._origText;

                const matchLead = node.nodeValue.match(/^\s+/);
                const lead = matchLead ? ' ' : '';
                const matchTrail = node.nodeValue.match(/\s+$/);
                const trail = matchTrail ? ' ' : '';

                if (lang === 'en') {
                    node.nodeValue = lead + node._origText + trail;
                } else if (dict && dict[lookupKey]) {
                    node.nodeValue = lead + dict[lookupKey] + trail;
                }
            }
        }
    });

    // Translate Sahayak welcome message if visible
    const botWelcome = document.getElementById('bot-welcome-msg');
    if (botWelcome) {
        if (lang === 'te') {
            botWelcome.innerHTML = `🙏 <strong>నమస్కారం!</strong> నేను మీ AI క్రాఫ్ట్ అడ్వైజర్ని. మీ ఉత్పత్తుల ర్యాంకింగ్, అమెజాన్ సింక్, న్యాయమైన వేతనాలు లేదా B2B హోల్‌సేల్ అవసరాల గురించి నన్ను ఏదైనా అడగండి!`;
        } else if (lang === 'hi') {
            botWelcome.innerHTML = `🙏 <strong>नमस्ते!</strong> मैं आपका एआई शिल्प सलाहकार हूँ। अपने उत्पादों की रैंकिंग, अमेज़ॅन सिंक, उचित मजदूरी या B2B थोक आवश्यकताओं के बारे में मुझसे कुछ भी पूछें!`;
        } else {
            botWelcome.innerHTML = `🙏 <strong>नमस्ते / Welcome!</strong> I am your AI Craft & Sales Advisor. Ask me anything about ranking your products, syncing to Amazon/Flipkart, calculating fair wages, or checking your cluster's B2B sales!`;
        }
    }
}

/**
 * Apply Multilingual Dictionary
 */
function applyTranslations(lang) {
    if (!lang) lang = 'en';
    currentLang = lang;
    document.documentElement.lang = lang;
    localStorage.setItem('vk_selected_lang', lang);

    const langSelect = document.getElementById('lang-select');
    if (langSelect && langSelect.value !== lang) {
        langSelect.value = lang;
    }

    const dict = i18n[lang] || i18n.en;

    for (const key in dict) {
        const val = dict[key];

        // 1. Direct ID match
        const el = document.getElementById(key);
        if (el) el.innerHTML = val;

        // 2. Alias ID match
        const aliases = keyAliases[key];
        if (aliases && aliases.length) {
            for (const aliasId of aliases) {
                const aEl = document.getElementById(aliasId);
                if (aEl) aEl.innerHTML = val;
            }
        }

        // 3. data-i18n attribute match
        document.querySelectorAll(`[data-i18n="${key}"]`).forEach(elem => {
            elem.innerHTML = val;
        });

        // 4. data-i18n-placeholder attribute match
        document.querySelectorAll(`[data-i18n-placeholder="${key}"]`).forEach(elem => {
            elem.setAttribute('placeholder', val);
        });
    }

    // Explicit placeholder for artisan notes input
    const notesInput = document.getElementById('artisan-notes-input');
    if (notesInput && dict.textOptionPlaceholder) {
        notesInput.setAttribute('placeholder', dict.textOptionPlaceholder);
    }

    // Translate full page DOM
    translateDOM(lang);
}

